#Numero
numero = 4

#numero elevado a la sexta
potencia = numero ** 6

#multiplicacion por 2
multiplicacion = numero * 2

#Resta
Resta = potencia - multiplicacion

#Residuo
Residuo = Resta % 5

#resultados
print(f"Numero inicial: {numero}")
print(f"Numero elevado a la sexta: {potencia}")
print(f"Numero multiplicado por 2: {multiplicacion}")
print(f"Resultado de la resta: {Resta}")
print(f"Residuo de dividir entre 5: {Residuo}")
