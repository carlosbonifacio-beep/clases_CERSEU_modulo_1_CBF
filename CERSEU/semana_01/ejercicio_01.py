nombre = "Carlos"
apellido_paterno = "Bonifacio"
apellido_materno = "Flores"

#concatenación
nombre_completo = nombre + " " + apellido_paterno + " " + apellido_materno

#saludo
mi_saludo = f"¡HI {nombre_completo}!"

#caracteres
total_caracteres = len(nombre_completo)

#resultados
print(f"Saludo: {mi_saludo}")
print(f"Nombre completo: {nombre_completo.upper()}")
print(f"Cantidad de caracteres: {total_caracteres}")


